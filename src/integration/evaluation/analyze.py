"""Descriptive summary of pilot logs (Phase 2, step 7 -> Dec 3 report).

Reads every eval_logs/participant_NN.csv and participant_NN_survey.csv and
prints a Markdown report: decisions, trust, confidence and decision time
per condition, per scenario and per block (order check), plus the exit
survey. Descriptive only, as in the team's evaluation plan: with 6-10
participants, read these as rates and distributions, not significance tests.

    PYTHONPATH=src python -m integration.evaluation analyze
    PYTHONPATH=src python -m integration.evaluation analyze --out report.md
"""

from __future__ import annotations

import csv
import re
from collections import Counter, defaultdict
from collections.abc import Iterable
from pathlib import Path
from statistics import mean, median

from .log import LOG_DIR
from .present import CONDITIONS
from .survey import QUESTIONS

_SESSION_FILE = re.compile(r"participant_(\d+)\.csv$")
DECISIONS = ("accept", "edit", "reject")


def load_rows(log_dir: Path = LOG_DIR) -> list[dict]:
    rows = []
    for path in sorted(log_dir.glob("participant_*.csv")):
        if not _SESSION_FILE.search(path.name):
            continue  # survey files
        with path.open(newline="", encoding="utf-8") as f:
            rows.extend(csv.DictReader(f))
    return rows


def load_survey(log_dir: Path = LOG_DIR) -> list[dict]:
    rows = []
    for path in sorted(log_dir.glob("participant_*_survey.csv")):
        with path.open(newline="", encoding="utf-8") as f:
            rows.extend(csv.DictReader(f))
    return rows


def _fmt(x: float | None, digits: int = 2) -> str:
    return "-" if x is None else f"{x:.{digits}f}"


def summarize(rows: Iterable[dict]) -> dict:
    rows = list(rows)
    n = len(rows)
    counts = Counter(r["decision"] for r in rows)
    trust = [int(r["trust"]) for r in rows]
    conf = [int(r["confidence"]) for r in rows]
    times = [float(r["decision_time_s"]) for r in rows]
    return {
        "n": n,
        **{d: (counts[d] / n if n else None) for d in DECISIONS},
        "trust": mean(trust) if trust else None,
        "confidence": mean(conf) if conf else None,
        "time_median": median(times) if times else None,
    }


def _summary_table(groups: dict[str, list[dict]], first_col: str) -> list[str]:
    lines = [
        (
            f"| {first_col} | n | accept | edit | reject | trust (mean) | confidence (mean) "
            "| decision time (median s) |"
        ),
        "|---|---|---|---|---|---|---|---|",
    ]
    for key, rows in groups.items():
        s = summarize(rows)
        pct = [("-" if s[d] is None else f"{s[d]:.0%}") for d in DECISIONS]
        lines.append(
            f"| {key} | {s['n']} | {' | '.join(pct)} | {_fmt(s['trust'])} | "
            f"{_fmt(s['confidence'])} | {_fmt(s['time_median'], 1)} |"
        )
    return lines


def _by(rows: list[dict], *keys: str) -> dict[str, list[dict]]:
    groups: dict[str, list[dict]] = defaultdict(list)
    for r in rows:
        groups[" / ".join(r[k] for k in keys)].append(r)
    return dict(sorted(groups.items()))


def _block(row: dict, per_block: dict[str, int]) -> str:
    """'first' or 'second' block of the session for this row."""
    half = per_block[row["participant"]]
    return "first block" if int(row["position"]) <= half else "second block"


def report(log_dir: Path = LOG_DIR) -> str:
    rows = load_rows(log_dir)
    survey = load_survey(log_dir)
    participants = sorted({r["participant"] for r in rows}, key=int)
    out = [
        "# Pilot results (descriptive)",
        "",
        f"Generated by `python -m integration.evaluation analyze` from `{log_dir}/`.",
        (
            f"Participants: {len(participants)} ({', '.join(participants) or 'none'}). "
            f"Scenario decisions: {len(rows)}. Survey answers: {len(survey)}."
        ),
        "",
    ]
    if not rows:
        out.append("No session logs found yet.")
        return "\n".join(out) + "\n"

    by_condition = {c: [r for r in rows if r["condition"] == c] for c in CONDITIONS}
    out += [
        "## By condition",
        "",
        "Trust and confidence are 1-7. Every participant sees both conditions.",
        "",
        *_summary_table(by_condition, "Condition"),
        "",
    ]

    # Per participant: explanation minus plain (within-subjects difference).
    out += [
        "## Within-participant difference (explanation minus plain)",
        "",
        "| Participant | trust diff | confidence diff | accept-rate diff |",
        "|---|---|---|---|",
    ]
    diffs = []
    for p in participants:
        mine = [r for r in rows if r["participant"] == p]
        e = summarize(r for r in mine if r["condition"] == "explanation")
        n = summarize(r for r in mine if r["condition"] == "plain")
        if not e["n"] or not n["n"]:
            out.append(f"| {p} | incomplete | incomplete | incomplete |")
            continue
        d = (e["trust"] - n["trust"], e["confidence"] - n["confidence"], e["accept"] - n["accept"])
        diffs.append(d)
        out.append(f"| {p} | {d[0]:+.2f} | {d[1]:+.2f} | {d[2]:+.0%} |")
    if diffs:
        higher = sum(1 for d in diffs if d[0] > 0)
        out += [
            "",
            (
                f"Mean trust difference: {mean(d[0] for d in diffs):+.2f}; "
                f"{higher} of {len(diffs)} participants trusted the explained scenarios more."
            ),
        ]
    out.append("")

    out += [
        "## By scenario and condition",
        "",
        *_summary_table(_by(rows, "scenario_id", "condition"), "Scenario / condition"),
        "",
        "## By what was decided on",
        "",
        (
            "`proposal_action` is empty for recommendation-only scenarios; `ask` is the "
            "planner's fallback when it is unsure."
        ),
        "",
        *_summary_table(
            _by(
                [{**r, "proposal_action": r["proposal_action"] or "(recommendation)"} for r in rows],
                "proposal_action",
                "condition",
            ),
            "Action / condition",
        ),
        "",
    ]

    per_block = {
        p: len([r for r in rows if r["participant"] == p]) // 2 for p in participants
    }
    blocks = defaultdict(list)
    for r in rows:
        blocks[f"{_block(r, per_block)} / {r['condition']}"].append(r)
    out += [
        "## Order check (first vs second block)",
        "",
        (
            "If the second block differs a lot from the first regardless of condition, "
            "practice or fatigue is in play."
        ),
        "",
        *_summary_table(dict(sorted(blocks.items())), "Block / condition"),
        "",
    ]

    edits = [r for r in rows if r["edit_note"].strip()]
    if edits:
        out += ["## Edit notes", ""]
        out += [f"- P{r['participant']} {r['scenario_id']} ({r['condition']}): {r['edit_note']}" for r in edits]
        out.append("")

    out += _survey_section(survey)
    return "\n".join(out) + "\n"


def _survey_section(survey: list[dict]) -> list[str]:
    if not survey:
        return ["## Exit survey", "", "No survey answers yet.", ""]
    answers: dict[str, list[tuple[str, str]]] = defaultdict(list)
    for r in survey:
        answers[r["question_id"]].append((r["participant"], r["answer"]))
    out = [
        "## Exit survey",
        "",
        "| Question | n | mean | median | min-max |",
        "|---|---|---|---|---|",
    ]
    for q in QUESTIONS:
        if q.kind != "likert":
            continue
        vals = [int(a) for _, a in answers[q.question_id] if a.isdigit()]
        if vals:
            out.append(
                f"| {q.text} | {len(vals)} | {mean(vals):.2f} | {median(vals):g} | "
                f"{min(vals)}-{max(vals)} |"
            )
    out.append("")
    for q in QUESTIONS:
        if q.kind == "choice":
            counts = Counter(a for _, a in answers[q.question_id])
            out += [f"**{q.text}**", ""]
            out += [f"- {c}: {counts[c]}" for c in q.choices]
            out.append("")
        elif q.kind == "text":
            given = [(p, a) for p, a in answers[q.question_id] if a.strip()]
            out += [f"**{q.text}**", ""]
            out += [f"- P{p}: {a}" for p, a in given] or ["- (no answers)"]
            out.append("")
    return out
